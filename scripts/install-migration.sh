#!/usr/bin/env bash
# 一次性转换只由安装、更新与旧更新器桥接调用；source 不执行迁移。

# 旧 resources 与首批 update 的 data 布局都使用 flock；交互 Shell 的
# 已加载函数无法通过 argv 排空发现。只等待已有锁，不新增 flock 依赖。
_install_legacy_profiles_lock_acquire() {
    local kind=$2 path path_id fd_id
    case $kind in
    legacy-v1) path=$1/resources/profiles.lock ;;
    current) path=$1/data/profiles.lock ;;
    *) return 0 ;;
    esac
    command -v flock >/dev/null 2>&1 || return 0
    [ -e "$path" ] || [ -L "$path" ] || return 0
    [ -f "$path" ] && [ ! -L "$path" ] &&
        [ "$(stat -c %u -- "$path")" = "$(id -u)" ] || return 1
    exec {legacy_profiles_fd}>>"$path" || return 1
    if ! { path_id=$(stat -c '%d:%i' -- "$path") &&
        fd_id=$(stat -Lc '%d:%i' -- "/proc/self/fd/$legacy_profiles_fd") &&
        [ ! -L "$path" ] && [ "$path_id" = "$fd_id" ]; }; then
        _install_legacy_profiles_lock_release
        return 1
    fi
    flock -w "${3:-60}" "$legacy_profiles_fd" || {
        _install_legacy_profiles_lock_release
        printf '旧版订阅操作尚未结束，请稍后重试迁移\n' >&2
        return 1
    }
}

_install_legacy_profiles_lock_release() {
    [ -n "${legacy_profiles_fd:-}" ] || return 0
    exec {legacy_profiles_fd}>&- || return 1
    legacy_profiles_fd=''
}

# Temporarily pause only this installation's explicit subscription jobs and the
# exact unscoped command generated by historical clashsub --auto. Other cron
# jobs, interactive shells and arbitrary user-created writers are left alone.

_install_maintenance_replace_home() {
    local text=$1 home=$2 replacement=$3 before after result='' found=false
    while [[ $text == *"$home"* ]]; do
        before=${text%%"$home"*}
        after=${text#*"$home"}
        case $before in
        '' | *[[:space:]\;\'\"=\(])
            case $after in
            '' | /* | [[:space:]\;\'\"\)]*)
                result+="$before$replacement"
                found=true
                ;;
            *) result+="$before$home" ;;
            esac
            ;;
        *) result+="$before$home" ;;
        esac
        text=$after
    done
    _INSTALL_MAINTENANCE_REWRITTEN=$result$text
    [ "$found" = true ]
}

_install_maintenance_shell() {
    case ${1##*/} in bash | sh | dash | zsh | ksh | fish) return 0 ;; esac
    return 1
}

_install_maintenance_update_command() {
    local text=$1
    text=${text//\'/ }
    text=${text//\"/ }
    text=${text//;/ }
    [[ $text =~ (^|[[:space:]])clashsub[[:space:]]+update([[:space:]]|$) ]] ||
        [[ $text =~ (^|[[:space:]])[^[:space:]]*clashctl([.]sh)?[[:space:]]+(sub[[:space:]]+update|update)([[:space:]]|$) ]]
}

_install_maintenance_cron_matches() {
    local line=$1 home=$2 minute hour day month weekday command executable resolved
    read -r minute hour day month weekday command <<<"$line"
    case $minute in '' | \#* | *=*) return 1 ;; esac
    case $command in
    "$home/"* | \""$home/"* | \'"$home/"*)
        _install_maintenance_update_command "$command" && return 0
        ;;
    esac
    [ "$minute $hour $day $month $weekday" = '0 0 */2 * *' ] || return 1
    executable=${command%% *}
    if [[ $executable == /* ]] && _install_maintenance_shell "$executable" &&
        [ "$command" = "$executable -i -c 'clashsub update'" ]; then
        return 0
    fi
    [ "$command" = "$executable sub update # clashctl-auto-update" ] || return 1
    [ "$executable" = clashctl ] && return 0
    resolved=$(readlink -f -- "$executable" 2>/dev/null) || return 1
    _install_maintenance_replace_home "$resolved" "$home" "$home"
}

_install_maintenance_read_cron() {
    local output=$1 rc=0
    LC_ALL=C crontab -l >"$output" 2>"$output.err" || rc=$?
    [ "$rc" -eq 0 ] && return 0
    if [ ! -s "$output" ] && { [ ! -s "$output.err" ] ||
        grep -Eq 'no crontab|No such file or directory' "$output.err"; }; then
        return 0
    fi
    printf '无法读取当前用户的订阅定时任务，未迁移旧目录\n' >&2
    return 1
}

# Inspect actual script/command arguments, never arbitrary shell source text.
# This intentionally cannot discover functions already loaded into idle shells.
_install_maintenance_process_matches() {
    local pid=$1 home=$2 argument script='' cwd index=0 command=''
    local -a argv=()
    { while IFS= read -r -d '' argument; do argv+=("$argument"); done <"/proc/$pid/cmdline"; } 2>/dev/null || return 1
    [ "${#argv[@]}" -gt 0 ] || return 1
    if _install_maintenance_shell "${argv[0]}"; then
        index=1
        while [ "$index" -lt "${#argv[@]}" ]; do
            argument=${argv[$index]}
            case $argument in
            -c)
                command=${argv[$((index + 1))]:-}
                [ "$command" = 'clashsub update' ] && return 0
                # Cron's outer /bin/sh command is the exact generated form.
                script=${command%% *}
                if [[ $script == /* ]] && _install_maintenance_shell "$script" &&
                    [ "$command" = "$script -i -c 'clashsub update'" ]; then
                    return 0
                fi
                return 1
                ;;
            --) index=$((index + 1)); break ;;
            -*) index=$((index + 1)) ;;
            *) break ;;
            esac
        done
    fi
    script=${argv[$index]:-}
    [ -n "$script" ] || return 1
    case ${script##*/} in install.sh | uninstall.sh | clashctl | clashctl.sh) ;; *) return 1 ;; esac
    if [[ $script != /* ]]; then
        cwd=$(readlink -- "/proc/$pid/cwd" 2>/dev/null) || return 1
        script=$cwd/$script
    fi
    script=$(readlink -f -- "$script" 2>/dev/null) || return 1
    case $script in
    "$home/install.sh" | "$home/uninstall.sh") return 0 ;;
    "$home/"*)
        index=$((index + 1))
        case ${argv[$index]:-}:${argv[$((index + 1))]:-} in
        update:* | sub:update) return 0 ;;
        esac
        ;;
    esac
    return 1
}

_install_maintenance_wait() {
    local home=$1 timeout=${2:-60} deadline=$((SECONDS + ${2:-60})) proc pid busy
    local ancestor=$BASHPID stat rest parent excluded=' '
    [ -d /proc/self ] || return 0
    while [ "$ancestor" -gt 1 ] 2>/dev/null; do
        excluded+="$ancestor "
        { IFS= read -r stat <"/proc/$ancestor/stat"; } 2>/dev/null || break
        rest=${stat##*) }
        read -r _ parent _ <<<"$rest"
        ancestor=$parent
    done
    while :; do
        busy=''
        for proc in /proc/[0-9]*; do
            pid=${proc##*/}
            [[ $excluded != *" $pid "* ]] || continue
            [ -O "$proc" ] || continue
            if _install_maintenance_process_matches "$pid" "$home"; then
                busy=$pid
                break
            fi
        done
        [ -n "$busy" ] || return 0
        if [ "$timeout" -eq 0 ] || [ "$SECONDS" -ge "$deadline" ]; then
            printf '旧版操作仍在运行（PID %s），本次未迁移旧目录；请稍后重试\n' "$busy" >&2
            return 1
        fi
        sleep 1 || return 1
    done
}

_install_maintenance_begin() {
    local home=$1 timeout=${2:-60} line
    if [ "${_INSTALL_MAINTENANCE_ACTIVE:-false}" = true ]; then
        [ "${_INSTALL_MAINTENANCE_HOME:-}" = "$home" ] || return 1
        _install_maintenance_wait "$home" "$timeout"
        return
    fi
    _install_maintenance_cleanup || return 1
    _INSTALL_MAINTENANCE_HOME=$home
    _INSTALL_MAINTENANCE_ACTIVE=false
    if command -v crontab >/dev/null 2>&1; then
        _INSTALL_MAINTENANCE_WORK=$(umask 077; mktemp -d "${TMPDIR:-/tmp}/clashctl-maintenance.XXXXXX") || return 1
        _install_maintenance_read_cron "$_INSTALL_MAINTENANCE_WORK/original" || return 1
        : >"$_INSTALL_MAINTENANCE_WORK/paused"
        : >"$_INSTALL_MAINTENANCE_WORK/removed"
        while IFS= read -r line || [ -n "$line" ]; do
            if _install_maintenance_cron_matches "$line" "$home"; then
                printf '%s\n' "$line" >>"$_INSTALL_MAINTENANCE_WORK/removed"
            else
                printf '%s\n' "$line" >>"$_INSTALL_MAINTENANCE_WORK/paused"
            fi
        done <"$_INSTALL_MAINTENANCE_WORK/original"
        if [ -s "$_INSTALL_MAINTENANCE_WORK/removed" ]; then
            # Set recovery state first: a signal during crontab must be reversible.
            _INSTALL_MAINTENANCE_ACTIVE=true
            crontab "$_INSTALL_MAINTENANCE_WORK/paused" || return 1
        fi
    fi
    _install_maintenance_wait "$home" "$timeout"
}

_install_maintenance_rehome_entry() {
    local line=$1 destination=$2 minute hour day month weekday command executable quoted_home quoted_body
    read -r minute hour day month weekday command <<<"$line"
    executable=${command%% *}
    if [ "$minute $hour $day $month $weekday" = '0 0 */2 * *' ] &&
        [ "$command" = "$executable sub update # clashctl-auto-update" ]; then
        # The new loader defines shell functions; it is not an executable CLI.
        printf -v quoted_home '%q' "$destination"
        # shellcheck disable=SC2016  # 新 Bash 加载器在执行任务时展开安装目录。
        printf -v quoted_body '%q' '. "$CLASHCTL_HOME/scripts/cmd/clashctl.sh" && clashsub update'
        _INSTALL_MAINTENANCE_ENTRY=${line%"$command"}"CLASHCTL_HOME=$quoted_home bash -c $quoted_body # clashctl-auto-update"
        _INSTALL_MAINTENANCE_ENTRY=${_INSTALL_MAINTENANCE_ENTRY//%/\\%}
    else
        _install_maintenance_replace_home "$line" "$_INSTALL_MAINTENANCE_HOME" "$destination" || true
        _INSTALL_MAINTENANCE_ENTRY=$_INSTALL_MAINTENANCE_REWRITTEN
    fi
}

_install_maintenance_apply() {
    local destination=$1 work=${_INSTALL_MAINTENANCE_WORK:-} line current_cron='' paused_cron=''
    local mode=${2:-restore}
    [ "${_INSTALL_MAINTENANCE_ACTIVE:-false}" = true ] || return 0
    _install_maintenance_read_cron "$work/current" || return 1
    IFS= read -r -d '' current_cron <"$work/current" || true
    IFS= read -r -d '' paused_cron <"$work/paused" || true
    if [ "$mode" = restore ] && [ "$current_cron" = "$paused_cron" ]; then
        cp -- "$work/original" "$work/merged" || return 1
    elif [ "$current_cron" = "$paused_cron" ]; then
        # Keep variable assignments in their original order: cron applies each
        # assignment only to the jobs following it.
        : >"$work/merged"
        while IFS= read -r line || [ -n "$line" ]; do
            if grep -Fqx -- "$line" "$work/removed"; then
                _install_maintenance_rehome_entry "$line" "$destination"
                line=$_INSTALL_MAINTENANCE_ENTRY
            fi
            printf '%s\n' "$line" >>"$work/merged"
        done <"$work/original"
    else
        cp -- "$work/current" "$work/merged" || return 1
        while IFS= read -r line || [ -n "$line" ]; do
            if [ "$mode" = finish ]; then
                _install_maintenance_rehome_entry "$line" "$destination"
                line=$_INSTALL_MAINTENANCE_ENTRY
            fi
            grep -Fqx -- "$line" "$work/merged" || printf '%s\n' "$line" >>"$work/merged"
        done <"$work/removed"
    fi
    crontab "$work/merged" || {
        printf '无法恢复订阅定时任务，原记录保留在：%s\n' "$work/original" >&2
        return 1
    }
    _INSTALL_MAINTENANCE_ACTIVE=false
}

_install_maintenance_restore() {
    _install_maintenance_apply "${_INSTALL_MAINTENANCE_HOME:-}"
}

_install_maintenance_finish() {
    _install_maintenance_apply "$1" finish
}

_install_maintenance_cleanup() {
    [ "${_INSTALL_MAINTENANCE_ACTIVE:-false}" != true ] || return 1
    [ -z "${_INSTALL_MAINTENANCE_WORK:-}" ] || command rm -rf -- "$_INSTALL_MAINTENANCE_WORK" || return 1
    unset _INSTALL_MAINTENANCE_HOME _INSTALL_MAINTENANCE_WORK _INSTALL_MAINTENANCE_ACTIVE
}

# 在安装事务内一次性转换数字 ID；日常订阅命令只读取 name 模型。
_install_migrate_profiles() (
    [ -f "$CLASH_PROFILES_META" ] || return 0
    "$BIN_YQ" '.' "$CLASH_PROFILES_META" >/dev/null || return 1
    "$BIN_YQ" -e '([.profiles // [] | .[] | select(has("id"))] | length) > 0' \
        "$CLASH_PROFILES_META" >/dev/null 2>&1 || return 0
    local original=$CLASH_PROFILES_META temporary count i url name use mapped
    temporary=$(mktemp "${original}.migrate.XXXXXX") || return 1
    trap 'rm -f -- "$temporary"' EXIT
    cp -p -- "$original" "$temporary" || return 1
    local CLASH_PROFILES_META=$temporary
    . "$CLASHCTL_SRC/scripts/cmd/sub.sh" || return 1
    count=$("$BIN_YQ" '.profiles // [] | length' "$temporary") || return 1
    for ((i = 0; i < count; i++)); do
        IDX=$i "$BIN_YQ" -e '.profiles[env(IDX)] | has("name")' "$temporary" >/dev/null 2>&1 && continue
        url=$(IDX=$i "$BIN_YQ" '.profiles[env(IDX)].url // ""' "$temporary") || return 1
        name=$(_sub_unique_name "$(_sub_default_name "$url")") || return 1
        IDX=$i PROFILE_NAME=$name "$BIN_YQ" -i '.profiles[env(IDX)].name = strenv(PROFILE_NAME)' "$temporary" || return 1
    done
    use=$("$BIN_YQ" '.use // "" | tostring' "$temporary") || return 1
    if [[ $use =~ ^[0-9]+$ ]]; then
        mapped=$(PROFILE_ID=$use "$BIN_YQ" '.profiles // [] | .[] | select((.id // "" | tostring) == strenv(PROFILE_ID)) | .name // ""' "$temporary" | head -n1)
        [ -n "$mapped" ] || {
            printf '订阅当前选择无对应记录（ID: %s），请检查 %s\n' "$use" "$original" >&2
            return 1
        }
        PROFILE_NAME=$mapped "$BIN_YQ" -i '.use = strenv(PROFILE_NAME)' "$temporary" || return 1
    fi
    "$BIN_YQ" -i 'del(.profiles[].id)' "$temporary" && mv -fT -- "$temporary" "$original"
)

# yq 同时处理 block/flow YAML；只重写本安装拥有的订阅文件前缀。
_install_migrate_profile_paths() {
    [ -f "$CLASH_PROFILES_META" ] || return 0
    OLD_PROFILE_DIR="^${1//./\\.}/(resources|data)/profiles/" NEW_PROFILE_DIR="$2/data/profiles/" \
        "$BIN_YQ" -i '.profiles[].path |= sub(strenv(OLD_PROFILE_DIR); strenv(NEW_PROFILE_DIR))' "$CLASH_PROFILES_META"
}

# 仅迁移明确指向本安装的旧 export/source 对；不改用户的其他 Shell 设置。
_install_migrate_shell_rc() (
    detect_rc
    local rc shell target temporary quoted parse_rc
    printf -v quoted '%q' "${2:-$CLASHCTL_HOME}"
    for shell in BASH ZSH; do
        rc=SHELL_RC_$shell
        rc=${!rc:-}
        [ -f "$rc" ] || continue
        target=$(readlink -f -- "$rc") || return 1
        temporary=$(mktemp "${target}.clashctl.XXXXXX") || return 1
        parse_rc=0
        CLASHCTL_RC_EXPORT="export CLASHCTL_HOME=$quoted" awk '
            BEGIN { expected=ENVIRON["CLASHCTL_RC_EXPORT"] }
            /^# >>> clashctl >>>$/ { managed=1 }
            /^# <<< clashctl <<<$/{ managed=0; print; next }
            managed { print; next }
            pending != "" {
                if ($0 == ". $CLASHCTL_HOME/scripts/cmd/clashctl.sh" ||
                    $0 == "[ -s \"$CLASHCTL_HOME/scripts/cmd/clashctl.sh\" ] && . \"$CLASHCTL_HOME/scripts/cmd/clashctl.sh\"") {
                    pending=""; removed=1; next
                }
                print pending; pending=""
            }
            $0 == expected { pending=$0; next }
            { print }
            END { if (pending != "") print pending; if (!removed) exit 2 }
        ' "$target" >"$temporary" || parse_rc=$?
        if [ "$parse_rc" -eq 2 ]; then rm -f -- "$temporary"; continue; fi
        [ "$parse_rc" -eq 0 ] || { rm -f -- "$temporary"; return 1; }
        if [ -n "${1:-}" ]; then
            cp -p -- "$target" "$1/rc-$shell" || return 1
            printf '%s\n' "$target" >"$1/rc-$shell.path" || return 1
        fi
        if ! { chmod "$(stat -c %a -- "$target")" "$temporary" &&
            _append_source_block "$temporary" && mv -fT -- "$temporary" "$target"; }; then
            rm -f -- "$temporary"
            return 1
        fi
    done
    rc=${SHELL_RC_FISH:-}
    if [ -f "$rc" ] && [ ! -L "$rc" ] &&
        [ "$(head -n 1 -- "$rc")" = "$CLASHCTL_FISH_MANAGED_MARKER" ] &&
        [ "$(sed -n '2p' "$rc")" = "$(CLASHCTL_HOME="${2:-$CLASHCTL_HOME}" _fish_home_export)" ]; then
        if [ -n "${1:-}" ]; then
            cp -p -- "$rc" "$1/rc-FISH" || return 1
            printf '%s\n' "$rc" >"$1/rc-FISH.path" || return 1
        fi
        local mode
        mode=$(stat -c %a -- "$rc") || return 1
        _write_fish_rc && chmod "$mode" "$rc" || return 1
    fi
)

_install_write_format() {
    local temporary
    temporary=$(mktemp "$CLASHCTL_HOME/.clashctl-format.XXXXXX") || return 1
    printf '1\n' >"$temporary" && chmod 0600 "$temporary" &&
        mv -fT -- "$temporary" "$CLASHCTL_HOME/.clashctl-format" || {
        rm -f -- "$temporary"; return 1;
    }
}

_install_migration_reload() {
    case $service_manager in
    systemd) systemctl daemon-reload ;;
    systemd-user) systemctl --user daemon-reload ;;
    *) return 0 ;;
    esac
}

# 只关闭服务子进程继承的副本，父事务持锁直至迁移或恢复完成。
_install_migration_start_service() (
    _install_legacy_profiles_lock_release || return 1
    if [ "$1" = true ]; then service_sudo_start; else service_start; fi
)

# 被源码更新器在提交前调用；失败时更新器先恢复源码，再由外层恢复迁移状态。
_install_migration_finish() {
    if [ "$nested" = true ]; then
        if [ -f "$work/service-unit" ]; then
            local temporary
            temporary=$(mktemp "${unit}.XXXXXX") || return 1
            if ! { sed "s#${home//./\\.}/bin/$kernel/$kernel#$home/bin/$kernel#g" \
                "$work/service-unit" >"$temporary" &&
                chmod "$(stat -c %a "$work/service-unit")" "$temporary" &&
                mv -fT -- "$temporary" "$unit"; }; then
                rm -f -- "$temporary"; return 1
            fi
            _install_migration_reload || return 1
        fi
        if [ "$state" = running ]; then
            _install_migration_start_service "$privileged" || return 1
            [ "$(service_state)" = running ] || return 1
            [ "$privileged" = true ] || service_main_pid >/dev/null || return 1
        fi
    fi
    _install_migrate_shell_rc "$work" && _install_write_format
}

_install_migration_restore_file() {
    local temporary
    temporary=$(mktemp "${2}.restore.XXXXXX") || return 1
    cp -p -- "$1" "$temporary" && mv -fT -- "$temporary" "$2" || {
        rm -f -- "$temporary"; return 1;
    }
}

_install_migration_restore() (
    local restored=true shell target current
    trap '' INT TERM HUP
    set +e
    if [ -f "$work/service-unit" ] && { [ -L "$unit" ] || { [ -e "$unit" ] &&
        ! cmp -s -- "$unit" "$work/service-unit" && ! _service_definition_is_owned "$unit"; }; }; then
        touch "$work/keep"
        printf '服务定义已被其他操作替换，未覆盖；请检查备份：%s\n' "$work" >&2
        return 1
    fi
    if [ "$nested" = true ] && [ "$stopped" = true ]; then
        if [ "$moved" = true ]; then
            service_stop_checked || restored=false
            current=$(service_state) || restored=false
            if [ "$current" = failed ]; then service_stop && current=$(service_state) || restored=false; fi
            [ "$current" = stopped ] && ! _service_privileged_marker_exists || restored=false
        fi
        if [ "$restored" = true ] && [ "$moved" = true ]; then
            rm -f -- "$home/bin/$kernel" && mv -T -- "$work/nested" "$home/bin/$kernel" || restored=false
        fi
        BIN_KERNEL=$old_binary
        if [ -f "$work/service-unit" ]; then
            _install_migration_restore_file "$work/service-unit" "$unit" && _install_migration_reload || restored=false
        fi
        if [ "$restored" = true ] && [ "$state" = running ] && ! service_is_active; then
            _install_migration_start_service "$privileged" || restored=false
        fi
    elif [ "$moved" = true ]; then
        rm -f -- "$home/bin/$kernel" && mv -T -- "$work/nested" "$home/bin/$kernel" || restored=false
        if [ -f "$work/service-unit" ]; then
            _install_migration_restore_file "$work/service-unit" "$unit" && _install_migration_reload || restored=false
        fi
    fi
    if [ -f "$work/profiles-before" ]; then
        _install_migration_restore_file "$work/profiles-before" "$CLASH_PROFILES_META" || restored=false
    fi
    for shell in BASH ZSH FISH; do
        if [ -f "$work/rc-$shell.path" ]; then
            IFS= read -r target <"$work/rc-$shell.path"
            _install_migration_restore_file "$work/rc-$shell" "$target" || restored=false
        fi
    done
    rm -f -- "$home/.clashctl-format" || restored=false
    if [ "$restored" != true ]; then
        touch "$work/keep"
        printf '迁移恢复未完成，请保留现场和备份：%s\n' "$work" >&2
        return 1
    fi
    printf '迁移未完成，已恢复原目录和服务状态\n' >&2
)

_install_migration_cleanup() {
    local rc=$?
    trap - EXIT ERR
    trap '' INT TERM HUP
    set +e
    if [ "$complete" != true ]; then _install_migration_restore || rc=1; fi
    if [ "$maintenance_owned" = true ]; then
        if [ "$complete" = true ]; then
            _install_maintenance_finish "$home" || { _install_maintenance_restore; rc=1; }
        else _install_maintenance_restore || rc=1; fi
        _install_maintenance_cleanup || rc=1
    fi
    if [ -z "$profile_pid" ] && [ "$profile_lock" = "${_DIRECTORY_LOCK_DIR:-}" ]; then
        profile_pid=${_DIRECTORY_LOCK_PID:-} profile_token=${_DIRECTORY_LOCK_TOKEN:-}
    fi
    _install_legacy_profiles_lock_release || rc=1
    [ -z "$profile_pid" ] || _directory_lock_release "$profile_lock" "$profile_pid" "$profile_token" || rc=1
    exit "$rc"
}

# 只处理已发布 updater 可能到达的现代安装。无 update 的 resources 布局由安装器接管。
# 平坦布局不查询或停止服务，也不执行内核；故障安装仍可更新脚本。
_install_migrate_current() (
    local stage=$1 method=$2 target=$3 work=$4 installed=${5:-false}
    local home=$CLASHCTL_HOME kernel old_binary nested=false moved=false stopped=false complete=false
    local state='' privileged=false unit='' profile_lock='' profile_pid='' profile_token='' legacy_profiles_fd=''
    local maintenance_owned=false unexpected path
    export CLASHCTL_SRC=$stage
    . "$stage/scripts/preflight.sh" || return 1
    kernel=${CLASHCTL_KERNEL:-mihomo}
    old_binary="$home/bin/$kernel"
    if [ -d "$old_binary" ]; then nested=true; old_binary="$old_binary/$kernel"; fi
    BIN_KERNEL=$old_binary
    trap _install_migration_cleanup EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    trap 'exit 129' HUP
    if [ "${_INSTALL_MAINTENANCE_ACTIVE:-false}" != true ] &&
        { [ "$installed" = true ] || ! grep -q '^_directory_lock_acquire()' "$home/scripts/lib/operation-lock.sh" 2>/dev/null; }; then
        maintenance_owned=true
        _install_maintenance_begin "$home" || return 1
    fi
    for path in "$home" "$CLASH_DATA_DIR" "$home/resources"; do
        _managed_directory_is_safe "$path" || { _ui_error "迁移目录无法安全使用：$path"; return 1; }
    done
    [ ! -e "$home/bin" ] && [ ! -L "$home/bin" ] || _managed_directory_is_safe "$home/bin" || return 1
    profile_lock="${CLASH_PROFILES_LOCK}.d"
    _directory_lock_acquire "$profile_lock" 0 || { _ui_error '订阅操作正在进行，稍后重试升级'; return 1; }
    profile_pid=$_DIRECTORY_LOCK_PID profile_token=$_DIRECTORY_LOCK_TOKEN
    _install_legacy_profiles_lock_acquire "$home" current || return 1
    if [ "$nested" = true ]; then
        _managed_directory_is_safe "$home/bin/$kernel" || return 1
        unexpected=$(find "$home/bin/$kernel" -mindepth 1 -maxdepth 1 ! -name "$kernel" -print -quit) || return 1
        [ -z "$unexpected" ] || { _ui_error "嵌套内核目录含其他文件：$unexpected"; return 1; }
        [ ! -L "$old_binary" ] || return 1
        detect_service_manager
        _service_check_conflict || return 1
        state=$(service_state) || { _ui_error '无法确认旧服务状态，请恢复服务管理器连接后重试'; return 1; }
        case $state in running | stopped | failed) ;; *) _ui_error '服务正在切换状态，稍后重试'; return 1 ;; esac
        _service_privileged_marker_exists && privileged=true
        unit=$(_service_target) || unit=''
        if [ -n "$unit" ] && { [ -e "$unit" ] || [ -L "$unit" ]; }; then
            [ ! -L "$unit" ] && _service_definition_is_owned "$unit" &&
                cp -p -- "$unit" "$work/service-unit" || return 1
        fi
        if [ "$state" = running ]; then
            [ "$privileged" = true ] || service_main_pid >/dev/null || return 1
            _require_base_config || return 1
            _component_file_is_safe "$old_binary" 755 &&
                timeout 15 "$old_binary" -d "$CLASH_RESOURCES_DIR" -f "$CLASH_CONFIG_RUNTIME" -t >/dev/null || {
                _ui_error '运行中的旧内核无法通过配置检查，请先停止服务或修复配置再升级'; return 1;
            }
        fi
    fi
    if [ -f "$CLASH_PROFILES_META" ]; then
        [ ! -L "$CLASH_PROFILES_META" ] && cp -p -- "$CLASH_PROFILES_META" "$work/profiles.pending" &&
            mv -T -- "$work/profiles.pending" "$work/profiles-before" || return 1
        _install_migrate_profiles || return 1
    fi
    if [ "$nested" = true ]; then
        if [ "$state" = running ]; then
            stopped=true
            service_stop_checked && [ "$(service_state)" = stopped ] && ! _service_privileged_marker_exists || return 1
        fi
        mv -T -- "$home/bin/$kernel" "$work/nested" || return 1
        moved=true
        [ ! -f "$work/nested/$kernel" ] || cp -p -- "$work/nested/$kernel" "$home/bin/$kernel" || return 1
        BIN_KERNEL="$home/bin/$kernel"
    fi
    local _INSTALL_UPDATE_FINISH=1
    if [ "$installed" = true ]; then _install_migration_finish || return 1;
    elif [ "$method" = git ]; then _update_git_checkout "$target" "$work" || return 1;
    else _update_archive "$stage" "$work" || return 1; fi
    complete=true
)

# 旧 updater 已替换源码才加载入口；此时只能恢复迁移的文件，不能追溯旧源码。
_install_bridge() (
    export CLASHCTL_SRC=$CLASHCTL_HOME
    CLASHCTL_INSTALL_RUNNING=1
    . "$CLASHCTL_HOME/scripts/install-common.sh" || return 1
    local work=''
    trap 'rc=$?; trap - EXIT ERR; [ -z "$work" ] || [ -f "$work/keep" ] || rm -rf -- "$work"; if declare -F operation_lock_release >/dev/null; then operation_lock_release || true; fi; exit "$rc"' EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    trap 'exit 129' HUP
    _install_lock "$CLASHCTL_HOME" || return 1
    _install_format_current && return 0
    [ "$(_install_existing_kind "$CLASHCTL_HOME")" = current ] || return 1
    work=$(mktemp -d "${CLASHCTL_HOME}.migrate.XXXXXX") || return 1
    _install_migrate_current "$CLASHCTL_HOME" '' '' "$work" true
)

# 迁移失败后的诊断入口只在独立 Bash 中解释旧路径，不向业务库引入双布局。
_install_recovery() (
    export CLASHCTL_SRC=$CLASHCTL_HOME
    . "$CLASHCTL_HOME/scripts/preflight.sh" || return 1
    if [ -d "$CLASHCTL_HOME/bin/$CLASHCTL_KERNEL" ]; then
        BIN_KERNEL="$CLASHCTL_HOME/bin/$CLASHCTL_KERNEL/$CLASHCTL_KERNEL"
    fi
    case ${1:-help} in
    status) detect_service_manager; service_state ;;
    log) service_log -n 50 ;;
    stop) operation_lock_acquire || return 1; trap operation_lock_release EXIT; service_stop_checked ;;
    *) printf '迁移未完成，请重试：bash "%s/install.sh" --home "%s"\n' "$CLASHCTL_HOME" "$CLASHCTL_HOME" >&2; return 1 ;;
    esac
)

# 只有桥接失败才装入这些当前 Shell 的命令；正常加载仅检查完成标记。
_install_recovery_shell() {
    _ui_fail() { printf '%s\n' "$*" >&2; }
    _ui_ok_out() { printf '%s\n' "$*"; }
    . "$CLASHCTL_HOME/scripts/cmd/off.sh"
    clashctl() {
        case ${1:-help} in
        off) shift; clashoff "$@" ;;
        update)
            bash "$CLASHCTL_HOME/install.sh" --home "$CLASHCTL_HOME" &&
                . "$CLASHCTL_HOME/scripts/cmd/clashctl.sh"
            ;;
        *) CLASHCTL_HOME="$CLASHCTL_HOME" bash -c '
            . "$CLASHCTL_HOME/scripts/install-migration.sh" && _install_recovery "$@"
        ' _ "$@" ;;
        esac
    }
    clashstatus() { clashctl status "$@"; }
    clashlog() { clashctl log "$@"; }
    clashstop() { clashctl stop "$@"; }
    clashupdate() { clashctl update "$@"; }
    local cmd_name
    for cmd_name in clashon clashstart clashui clashsub clashnode clashtun clashmixin clashsecret clashupgrade clashversion clashhelp; do
        eval "$cmd_name() { clashctl help; }"
    done
}
